    [Fact]
    public async Task IsIdentity()
    {
        //Arrange
        await using var conn = await OpenConnectionAsync();
        await IgnoreOnRedshift(conn, "Identity columns not support on Redshift");
        MinimumPgVersion(conn, "10.0", "IDENTITY introduced in PostgreSQL 10");
        var table = await CreateTempTable(
            conn,
            "identity1 INT GENERATED BY DEFAULT AS IDENTITY, identity2 INT GENERATED ALWAYS AS IDENTITY, serial SERIAL, int INT");

        await using var cmd = new PgSqlCommand($"SELECT identity1, identity2, serial, int, 8 FROM {table}", conn);
        await using var reader = await cmd.ExecuteReaderAsync(CommandBehavior.SchemaOnly | CommandBehavior.KeyInfo, cancellationToken: TestContext.Current.CancellationToken);

        //Act
        var rows = (await GetSchemaTable(reader)).Rows;

        //Assert
        rows[0]["IsIdentity"].Should().Be(true);
        rows[1]["IsIdentity"].Should().Be(true);
        rows[2]["IsIdentity"].Should().Be(false);
        rows[3]["IsIdentity"].Should().Be(false);
        rows[4]["IsIdentity"].Should().Be(false);
    }

    [Fact]
    public async Task IsReadOnly()
    {
        //Arrange
        using var conn = await OpenConnectionAsync();
        var table = await GetTempTableName(conn);
        var view = await GetTempViewName(conn);

        await conn.ExecuteNonQueryAsync($@"
CREATE TABLE {table} (id SERIAL PRIMARY KEY, int2 SMALLINT);
CREATE OR REPLACE VIEW {view} (id, int2) AS SELECT id, int2 + int2 AS int2 FROM {table}", cancellationToken: TestContext.Current.CancellationToken);

        var command = new PgSqlCommand($"SELECT id, int2 FROM {view}", conn);

        using var dr = command.ExecuteReader(CommandBehavior.SchemaOnly | CommandBehavior.KeyInfo);
        var metadata = await GetSchemaTable(dr);

        //Act
        var idRow = metadata.Rows.OfType<DataRow>().FirstOrDefault(x => (string)x["ColumnName"] == "id");

        //Assert
        idRow.Should().NotBeNull("Unable to find metadata for id column");
        var int2Row = metadata.Rows.OfType<DataRow>().FirstOrDefault(x => (string)x["ColumnName"] == "int2");
        int2Row.Should().NotBeNull("Unable to find metadata for int2 column");

        ((bool)idRow["IsReadonly"]).Should().BeFalse();
        ((bool)int2Row["IsReadonly"]).Should().BeTrue();
    }

    // ReSharper disable once InconsistentNaming
    [Fact]
    public async Task AllowDBNull()
    {
        //Arrange
        using var conn = await OpenConnectionAsync();
        var table = await CreateTempTable(conn, "nullable INTEGER, non_nullable INTEGER NOT NULL");

        using var cmd = new PgSqlCommand($"SELECT * FROM {table}", conn);
        using var reader = await cmd.ExecuteReaderAsync(CommandBehavior.SchemaOnly | CommandBehavior.KeyInfo, cancellationToken: TestContext.Current.CancellationToken);
        using var metadata = await GetSchemaTable(reader);

        //Act
        var nullableRow = metadata.Rows.OfType<DataRow>().FirstOrDefault(x => (string)x["ColumnName"] == "nullable");

        //Assert
        nullableRow.Should().NotBeNull("Unable to find metadata for nullable column");
        var nonNullableRow = metadata.Rows.OfType<DataRow>().FirstOrDefault(x => (string)x["ColumnName"] == "non_nullable");
        nonNullableRow.Should().NotBeNull("Unable to find metadata for non_nullable column");

        ((bool)nullableRow["AllowDBNull"]).Should().BeTrue();
        ((bool)nonNullableRow["AllowDBNull"]).Should().BeFalse();
    }

    [Fact, IssueLink("https://github.com/npgsql/npgsql/issues/1027")]
    public async Task without_result()
    {
        //Arrange
        using var conn = await OpenConnectionAsync();
        using var cmd = new PgSqlCommand("SELECT 1", conn);
        using var reader = await cmd.ExecuteReaderAsync(TestContext.Current.CancellationToken);
