    [Theory]
    [InlineData(PrepareOrNot.NotPrepared)]
    [InlineData(PrepareOrNot.Prepared)]
    public async Task schema_only(PrepareOrNot prepare)
    {
        // if (prepare == PrepareOrNot.Prepared && IsMultiplexing)
        //     return;

        using var conn = await OpenConnectionAsync();
        var table = await CreateTempTable(conn, "name TEXT");

        var query = $@"
SELECT 1 AS some_column;
UPDATE {table} SET name='yo' WHERE 1=0;
SELECT 1 AS some_other_column, 2";

        using var cmd = new PgSqlCommand(query, conn);
        if (prepare == PrepareOrNot.Prepared)
            cmd.Prepare();
        using (var reader = await cmd.ExecuteReaderAsync(CommandBehavior.SchemaOnly, cancellationToken: TestContext.Current.CancellationToken))
        {
            reader.Read().Should().BeFalse();
            var t = await GetSchemaTable(reader);
            t.Rows[0]["ColumnName"].Should().Be("some_column");
            reader.NextResult().Should().BeTrue();
            reader.Read().Should().BeFalse();
            t = await GetSchemaTable(reader);
            t.Rows[0]["ColumnName"].Should().Be("some_other_column");
            t.Rows[1]["ColumnName"].Should().Be("?column?");
            reader.NextResult().Should().BeFalse();
        }

        // Close reader in the middle
        using (var reader = await cmd.ExecuteReaderAsync(CommandBehavior.SchemaOnly, cancellationToken: TestContext.Current.CancellationToken))
            reader.Read();
    }

    [Fact]
    public async Task BaseColumnName()
    {
        //Arrange
        using var conn = OpenConnection();

        conn.ExecuteNonQuery(@"
                CREATE TEMP TABLE data (
                    Cod varchar(5) NOT NULL,
                    Descr varchar(40),
                    Date date,
                    CONSTRAINT PK_test_Cod PRIMARY KEY (Cod)
                );
            ");

        var cmd = new PgSqlCommand("SELECT Cod as CodAlias, Descr as DescrAlias, Date FROM data", conn);

        using var dr = cmd.ExecuteReader(CommandBehavior.SchemaOnly | CommandBehavior.KeyInfo);

        //Act
        var dt = await GetSchemaTable(dr);

        //Assert
        dt.Rows[0]["BaseColumnName"].ToString().Should().Be("cod");
        dt.Rows[0]["ColumnName"].ToString().Should().Be("codalias");
        dt.Rows[1]["BaseColumnName"].ToString().Should().Be("descr");
        dt.Rows[1]["ColumnName"].ToString().Should().Be("descralias");
        dt.Rows[2]["BaseColumnName"].ToString().Should().Be("date");
        dt.Rows[2]["ColumnName"].ToString().Should().Be("date");
    }

    async Task<DataTable> GetSchemaTable(PgSqlDataReader dr) => IsAsync ? await dr.GetSchemaTableAsync() : dr.GetSchemaTable();
}

